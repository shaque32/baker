"""Generate synthetic case03: two Cellebrite-style Excel reports, the mock affidavit, the DRAFT
answer key and the DRAFT assumption sheet. SYNTHETIC data only; deterministic for a seed.

case03 measures a challenge step (counter-evidence on claims close to supported). It is not
wired into `make eval` or any gate. Its key and sheet are drafts until Arsh signs them; nothing
here writes under eval/gold/.

Usage: python -m eval.synthetic.case03_generate [--out eval/synthetic/case03]

Outputs in --out:
  item1.xlsx, item2.xlsx   one Cellebrite-style report per phone (gitignored; case.json pins them)
  case.json                metadata, devices, source hashes, plants with their record ids
  affidavit_draft.md       the mock affidavit, numbered paragraphs
  draft_gold.jsonl         DRAFT answer key in GoldClaim format
  draft_assumptions.jsonl  DRAFT assumption sheet, the format run_pipeline --assumption-spec reads
  ANSWER_KEY_DRAFT.md      every claim, its plant, the cited rows and why each counter-record is
                           out of the fixed retrieval's reach
  SIGNING_SHEET.md         the short version for Arsh to sign
"""

