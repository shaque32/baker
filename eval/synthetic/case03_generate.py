def _write(path: Path, text: str) -> None:
    path.write_text(text, encoding="utf-8", newline="\n")  # the same bytes on every OS


def generate(out: Path, db: Path | None = None, seed: int = SEED) -> list[Rendered]:
    """Write every case03 output into out. db is accepted for run_pipeline's signature and
    ignored: case03 has no expected-database fixture."""
    del db
    out.mkdir(parents=True, exist_ok=True)
    rendered = build(seed)
    for r in rendered:
        write_xlsx(out / f"{r.device.key}.xlsx", r.sheets)
    gold = draft_gold(rendered)
    _write(
        out / "case.json", json.dumps(case_json(rendered, out), indent=2, ensure_ascii=False) + "\n"
    )
    _write(out / "affidavit_draft.md", render_affidavit())
    _write(out / "draft_gold.jsonl", "".join(g.model_dump_json() + "\n" for g in gold))
    _write(out / "draft_assumptions.jsonl", render_sheet_jsonl())
    _write(out / "ANSWER_KEY_DRAFT.md", render_answer_key(rendered, gold))
    _write(out / "SIGNING_SHEET.md", render_signing_sheet(gold))
    return rendered


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--out", type=Path, default=DEFAULT_OUT)
    args = parser.parse_args(argv)
    rendered = generate(args.out)
    total = sum(len(r.messages) for r in rendered)
    print(f"case03: {total} messages across {len(rendered)} devices -> {args.out}")
    return 0


