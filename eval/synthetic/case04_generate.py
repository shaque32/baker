# ---------------------------------------------------------------- rendering


def _offset(dev: story.Device, utc: datetime) -> int:
    if dev.report_tz == "utc":
        return 0
    if dev.report_tz == "fixed-360":
        return -360
    return story.central_offset_min(utc)


def _contact_name(dev: story.Device, identifier: str) -> str | None:
    phone = phone_of(identifier)
    for name, entries in dev.contacts:
        for _, value in entries:
            if value == identifier or (phone and value == phone):
                return name
    return None


def _name(dev: story.Device, acct: story.Acct, at: datetime) -> str | None:
    if acct.app == "Telegram":
        return acct.name_at(at)
    return _contact_name(dev, acct.identifier)


def _display(dev: story.Device, acct: story.Acct, at: datetime) -> str:
    if acct.key in dev.owner_accounts:
        return f"{acct.identifier} (owner)"
    name = _name(dev, acct, at)
    return f"{acct.identifier} {name}" if name else acct.identifier


def _account(r: Rendered, app: str, acct: story.Acct, locator: str, at: datetime) -> str:
    k = (app, acct.identifier)
    if k not in r.accounts:
        owned = acct.key in r.device.owner_accounts
        r.accounts[k] = {
            "id": f"acct:{r.device.key}:{app}:{acct.identifier}",
            "locator": locator,
            "app": app,
            "identifier": acct.identifier,
            "display_name": None if owned else _name(r.device, acct, at),
            "owned": owned,
        }
    return r.accounts[k]["id"]


def _summary(dev: story.Device) -> list[Row]:
    return [
        ["Summary (SYNTHETIC: all data fictional, generated by eval/synthetic)"],
        ["Case number", CASE_NUMBER],
        ["Evidence number", dev.evidence_no],
        ["Device", dev.model],
        ["OS version", dev.os_version],
        ["Extraction type", dev.extraction_label],
        ["Extraction start date/time", fmt_ts(dev.extracted_at, _offset(dev, dev.extracted_at))],
        ["Time zone", REPORT_TIME_LABEL[dev.report_tz]],
        ["Device time zone", story.DEVICE_TZ],
        ["Report version", f"baker-synth {GENERATOR_VERSION} (Cellebrite-style layout)"],
        ["Tool", TOOL_NAME],
        ["Tool version", GENERATOR_VERSION],
    ]


def render_device(dev: story.Device, msgs: list[story.Msg], calls: list[story.Call]) -> Rendered:
    """The same report layout as case01 and case03, from case04's story. A record whose skip
    names this phone is left out of its report (the phone did not keep it, or the extraction
    did not reach it)."""
    r = Rendered(dev)
    acc = story.ACCOUNTS
    src = dev.key
    owned = set(dev.owner_accounts)
    r.sheets.append(("Summary", _summary(dev)))
    r.device_row = 4

    acct_rows: list[Row] = [["User Accounts"], ACCOUNT_COLUMNS]
    for i, k in enumerate(dev.owner_accounts, start=1):
        a = acc[k]
        name = a.name_at(dev.extracted_at) if a.app == "Telegram" else None
        acct_rows.append([i, a.app, a.identifier, name or ""])
        _account(r, a.app, a, f"User Accounts!{TITLE_ROWS + i}", dev.extracted_at)
    r.sheets.append(("User Accounts", acct_rows))

    contact_rows: list[Row] = [["Contacts"], CONTACT_COLUMNS]
    for i, (name, entries) in enumerate(dev.contacts, start=1):
        row = TITLE_ROWS + i
        entry_text = "\n".join(f"{label}: {value}" for label, value in entries)
        source = "Telegram" if all(lbl.endswith("Telegram") for lbl, _ in entries) else "Phone"
        contact_rows.append([i, name, entry_text, source, "Intact"])
        ids = []
        for j, (_, value) in enumerate(entries, start=1):
            cid = f"contact:{src}:Contacts!{row}#{j}"
            r.contacts.append(
                {"id": cid, "locator": f"Contacts!{row}", "name": name, "identifier": value}
            )
            ids.append(cid)
        r.keys[f"contact:{name}"] = ids
    r.sheets.append(("Contacts", contact_rows))

    mine = [m for m in msgs if (m.sender in owned or m.to in owned) and src not in m.skip]
    threads: dict[tuple[str, str], list[story.Msg]] = {}
    for m in mine:
        other = m.to if m.sender in owned else m.sender
        threads.setdefault((acc[m.sender].app, other), []).append(m)
    ordered = sorted(threads.items(), key=lambda kv: (min(x.at for x in kv[1]), kv[0]))
    chat_rows: list[Row] = [["Chats"], CHAT_COLUMNS]
    n = 0
    for chat_no, ((app, other_key), tmsgs) in enumerate(ordered, start=1):
        other = acc[other_key]
        owner = acc[next(x.sender if x.sender in owned else x.to for x in tmsgs)]
        participants = (
            f"{_display(dev, owner, dev.extracted_at)}\n{_display(dev, other, dev.extracted_at)}"
        )
        chat_name = _name(dev, other, dev.extracted_at) or other.identifier
        thread_id = f"thr:{src}:{app}:{chat_no}"
        r.threads.append(
            {
                "id": thread_id,
                "locator": f"Chats!{TITLE_ROWS + n + 1}",
                "app": app,
                "title": chat_name,
            }
        )
        for m in sorted(tmsgs, key=lambda x: (x.at, x.key)):
            n += 1
            loc = f"Chats!{TITLE_ROWS + n}"
            offset = _offset(dev, m.at)
            raw = fmt_ts(m.at, offset)
            outgoing = m.sender in owned
            sender, to = acc[m.sender], acc[m.to]
            from_cell, to_cell = _display(dev, sender, m.at), _display(dev, to, m.at)
            chat_rows.append(
                [
                    n,
                    chat_no,
                    chat_name,
                    app,
                    other.identifier,
                    participants,
                    from_cell,
                    to_cell,
                    m.body,
                    raw,
                    "Outgoing" if outgoing else "Incoming",
                    "Intact",
                    "",
                    m.tag or "",
                ]
            )
            mid = f"msg:{src}:{loc}"
            r.messages.append(
                {
                    "id": mid,
                    "locator": loc,
                    "thread_id": thread_id,
                    "sender_account_id": _account(r, app, sender, loc, m.at),
                    "recipient_account_id": _account(r, app, to, loc, m.at),
                    "from_cell": from_cell,
                    "to_cell": to_cell,
                    "direction": "outgoing" if outgoing else "incoming",
                    "ts_utc": iso(m.at),
                    "ts_offset_min": offset,
                    "ts_raw": raw,
                    "body": m.body,
                    "lang": m.lang,
                    "tag": m.tag,
                    "app": app,
                    "key": m.key,
                }
            )
            r.keys.setdefault(m.key, []).append(mid)
    r.sheets.append(("Chats", chat_rows))

    call_rows: list[Row] = [["Call Log"], CALL_COLUMNS]
    mine_calls = sorted(
        (c for c in calls if (c.caller in owned or c.callee in owned) and src not in c.skip),
        key=lambda c: (c.at, c.key),
    )
    for i, c in enumerate(mine_calls, start=1):
        loc = f"Call Log!{TITLE_ROWS + i}"
        offset = _offset(dev, c.at)
        raw = fmt_ts(c.at, offset)
        if c.caller in owned:
            direction = "outgoing"
        else:
            direction = "incoming" if c.answered else "missed"
        caller, callee = acc[c.caller], acc[c.callee]
        from_cell, to_cell = _display(dev, caller, c.at), _display(dev, callee, c.at)
        call_rows.append(
            [
                i,
                "Phone",
                direction.capitalize(),
                raw,
                fmt_duration(c.duration_s),
                from_cell,
                to_cell,
                "Intact",
            ]
        )
        cid = f"call:{src}:{loc}"
        r.calls.append(
            {
                "id": cid,
                "locator": loc,
                "app": "Phone",
                "from_account_id": _account(r, "Phone", caller, loc, c.at),
                "to_account_id": _account(r, "Phone", callee, loc, c.at),
                "from_cell": from_cell,
                "to_cell": to_cell,
                "direction": direction,
                "ts_utc": iso(c.at),
                "ts_offset_min": offset,
                "ts_raw": raw,
                "duration_s": c.duration_s,
                "key": c.key,
            }
        )
        r.keys.setdefault(c.key, []).append(cid)
    r.sheets.append(("Call Log", call_rows))
    return r


def build(seed: int = SEED) -> list[Rendered]:
    filler_msgs, filler_calls = story.make_filler(seed)
    msgs = list(story.SCRIPTED_MESSAGES) + filler_msgs
    calls = list(story.SCRIPTED_CALLS) + filler_calls
    return [render_device(d, msgs, calls) for d in story.DEVICES]


# ---------------------------------------------------------------- affidavit


def affidavit_paragraphs() -> list[tuple[int, int, str]]:
    claims = {c.claim_id: c.text for c in key.CLAIMS}
    return [
        (page, no, " ".join(claims.get(p, p) for p in parts))
        for no, (page, parts) in enumerate(key.AFFIDAVIT, start=1)
    ]


def claim_location() -> dict[str, tuple[int, int]]:
    loc = {}
    for no, (page, parts) in enumerate(key.AFFIDAVIT, start=1):
        for p in parts:
            if p.startswith("C") and p[1:].isdigit():
                loc[p] = (page, no)
    return loc


def render_affidavit() -> str:
    lines = [
        "# Mock affidavit (SYNTHETIC DRAFT): case04",
        "",
        "Every name, number, agency and event in this document is fictional. Generated from",
        "`eval/synthetic/case04_key.py`; edit there, not here. Draft for Arsh's review.",
        "",
    ]
    page = 0
    for p, no, text in affidavit_paragraphs():
        if p != page:
            page = p
            lines += [f"## Page {page}", ""]
        lines += [f"{no}. {text}", ""]
    return "\n".join(lines)


def write_affidavit_pdf(path: Path) -> Path:
    """The mock affidavit as a PDF, laid out like the case01 one (eval/run_pipeline.py)."""
    from eval.synthetic import govdocs as g

    pages: list[list[tuple[float, float, str]]] = [[]]
    y = g.TOP
    page_no = 1
    for x, text in g._lines(g.Para("AFFIDAVIT (SYNTHETIC CASE04, NOT A REAL CASE)", heading=True)):
        pages[-1].append((x, y, text))
        y += g.LEADING
    y += g.PARA_GAP
    for page, no, text in affidavit_paragraphs():
        if page != page_no and pages[-1]:
            pages.append([])
            y = g.TOP
            page_no = page
        for x, line in g._lines(g.Para(text, no)):
            if y > g.BOTTOM:
                pages.append([])
                y = g.TOP
            pages[-1].append((x, y, line))
            y += g.LEADING
        y += g.PARA_GAP
    path.parent.mkdir(parents=True, exist_ok=True)
    g._write(pages, path, "AFFIDAVIT (SYNTHETIC CASE04)")
    return path


# ---------------------------------------------------------------- draft key and sheet


def resolve(rendered: list[Rendered], refs: tuple[key.Ref, ...]) -> list[str]:
    by_dev = {r.device.key: r for r in rendered}
    ids: list[str] = []
    for dev, k in refs:
        found = by_dev[dev].keys.get(k)
        if not found:
            raise KeyError(f"evidence {dev}:{k} not found in generated data")
        ids += found
    return ids


def draft_gold(rendered: list[Rendered]) -> list[GoldClaim]:
    loc = claim_location()
    return [
        GoldClaim(
            claim_id=c.claim_id,
            page=loc[c.claim_id][0],
            para_no=loc[c.claim_id][1],
            text=c.text,
            claim_type=c.claim_type,
            cross_device=c.cross_device,
            gold_verdict=c.verdict,
            core_assumptions=c.core_assumptions,
            key_evidence=tuple(resolve(rendered, c.evidence)),
            trap=c.hazard,
            rationale=c.rationale,
            labeled_by=key.DRAFT_LABEL,
            labeled_at=DRAFT_LABELED_AT,
        )
        for c in key.CLAIMS
    ]


def sheet_rows() -> list[dict]:
    """One assumption per line: claim_id, template_id, params, is_core (what run_pipeline reads)
    plus the review fields expected_check, note, labeled_by and template_version."""
    return [
        {
            "claim_id": spec.claim_id,
            "template_id": a.template_id,
            "template_version": key.TEMPLATES_VERSION,
            "is_core": a.is_core,
            "params": a.params,
            "expected_check": a.expect,
            "note": a.note,
            "labeled_by": key.DRAFT_LABEL,
        }
        for spec in key.SHEET
        for a in spec.assumptions
    ]


def render_sheet_jsonl() -> str:
    return "".join(
        json.dumps(row, ensure_ascii=False, sort_keys=True) + "\n" for row in sheet_rows()
    )


def no_checkable_core() -> list[str]:
    """Claims whose every core row is one no deterministic check tests (expected_check None)."""
    return [
        s.claim_id
        for s in key.SHEET
        if not any(a.is_core and a.expect is not None for a in s.assumptions)
    ]


def _row_index(rendered: list[Rendered]) -> dict[str, dict]:
    idx: dict[str, dict] = {}
    for r in rendered:
        for m in r.messages:
            idx[m["id"]] = {"kind": "message", **m}
        for c in r.calls:
            idx[c["id"]] = {"kind": "call", **c}
        for c in r.contacts:
            idx[c["id"]] = {"kind": "contact", **c}
    return idx


def _cell(text: str) -> str:
    return text.replace("|", "/").replace("\n", " ")


def _record_line(rid: str, row: dict, role: str) -> str:
    if row["kind"] == "message":
        return (
            f"| `{rid}` | {role} | {row['ts_raw']} | {row['app']} {_cell(row['from_cell'])} | "
            f"{_cell(row['to_cell'])} | {_cell(row['body'])} |"
        )
    if row["kind"] == "call":
        return (
            f"| `{rid}` | {role} | {row['ts_raw']} | {row['app']} {_cell(row['from_cell'])} | "
            f"{_cell(row['to_cell'])} | {row['direction']} call, "
            f"{fmt_duration(row['duration_s'])} |"
        )
    return f"| `{rid}` | {role} |  | contact | | {row['name']}: {row['identifier']} |"


def _count(items: list[str], keys: tuple[str, ...]) -> dict[str, int]:
    return {k: items.count(k) for k in keys}


def count_tables() -> list[str]:
    """The design counts, from the key itself: type x verdict, type x wording, hazards by kind
    and verdict, and the claims with no sheet or no checkable core row."""
    verdicts = ("supported", "contradicted", "unproven")
    wordings = ("plain", "affidavit")
    claims = key.CLAIMS
    out = [
        "### Claim type x draft verdict",
        "",
        "| Type | supported | contradicted | unproven | Total |",
        "|---|---|---|---|---|",
    ]
    for t in key.CLAIM_TYPES:
        row = _count([c.verdict for c in claims if c.claim_type == t], verdicts)
        out.append(
            f"| {t} | " + " | ".join(str(row[v]) for v in verdicts) + f" | {sum(row.values())} |"
        )
    tot = _count([c.verdict for c in claims], verdicts)
    out.append(
        "| **all** | " + " | ".join(f"**{tot[v]}**" for v in verdicts) + f" | **{len(claims)}** |"
    )
    out += [
        "",
        "### Claim type x wording",
        "",
        "| Type | plain | affidavit |",
        "|---|---|---|",
    ]
    for t in key.CLAIM_TYPES:
        row = _count([c.wording for c in claims if c.claim_type == t], wordings)
        out.append(f"| {t} | {row['plain']} | {row['affidavit']} |")
    wtot = _count([c.wording for c in claims], wordings)
    out.append(f"| **all** | **{wtot['plain']}** | **{wtot['affidavit']}** |")
    out += [
        "",
        "### Wording x draft verdict",
        "",
        "| Wording | supported | contradicted | unproven |",
        "|---|---|---|---|",
    ]
    for w in wordings:
        row = _count([c.verdict for c in claims if c.wording == w], verdicts)
        out.append(f"| {w} | " + " | ".join(str(row[v]) for v in verdicts) + " |")
    out += [
        "",
        "### Hazards by kind",
        "",
        "| Hazard | What the wrong reading is | Claims | supported | contradicted | unproven |",
        "|---|---|---|---|---|---|",
    ]
    for h, what in key.HAZARDS.items():
        hc = [c for c in claims if c.hazard == h]
        row = _count([c.verdict for c in hc], verdicts)
        out.append(
            f"| {h} | {what} | {len(hc)} | " + " | ".join(str(row[v]) for v in verdicts) + " |"
        )
    with_hazard = sum(c.hazard != "none" for c in claims)
    out += [
        "",
        f"Claims with a planted wrong reading: {with_hazard} of {len(claims)}.",
        "",
        "### Claims without a sheet",
        "",
    ]
    if key.NO_SHEET:
        out += [f"- {cid}: {why}" for cid, why in key.NO_SHEET.items()]
    else:
        out.append("None: every claim has rows in `draft_assumptions.jsonl`.")
    out += [
        "",
        "### Claims with no checkable core row",
        "",
        "Their only core rows are ones no deterministic check tests, so only expert review",
        "covers them:",
        "",
    ]
    out += [
        f"- {cid} ({next(c.claim_type for c in claims if c.claim_id == cid)})"
        for cid in no_checkable_core()
    ]
    return out


