"""Records that rule an assumption out: other values, corrections, denials, negations, states.

Tags: value (an exclusive value; the assumption carries the other one, {v} -> {m}), corr (a plain
value the same sender later corrects in `fix`, whose correcting words are `fixq`; the assumption
carries the original, {v} -> {n}), deny (the sender denies the act in `vp` after the question in
`ask`), neg (the assumption's words inside a negation), state (a place or state, held since a
named day, that cannot hold together with the assumption on the record's own date).

Time scope (guide rule 23): an assumption claims no more time than the record speaks to. A fact
carries the record's own time ("today" -> {xdate}, "yesterday" -> {xprev}, "friday" -> {day})
or none when the record names none; a question about "yesterday" is answered for yesterday, so
its denial rules out yesterday, never "that day" with hours still to come.
"""

from __future__ import annotations

from eval.heldout.registry import Tpl, tpl

_OTHER = {"n": "m", "place": "place2", "day": "day2"}
_SAME = {"n": "n", "place": "place", "day": "day"}
_FIX_LEADS = (
    "no wait, ",
    "wait, ",
    "sorry, ",
    "correction, ",
    "my bad, ",
    "actually ",
    "scratch that, ",
    "стоп, ",
    "поправка, ",
    "сорри, ",
)


def fix_quote(fix: str, kind: str) -> str:
    """The correcting words of a fix: the replacement and the value it replaces ("booth {m},
    not {n}"), without the lead-in ("sorry,") or the excuse after them ("i misread the map")."""
    text = fix
    for lead in _FIX_LEADS:
        if text.startswith(lead):
            text = text[len(lead) :]
            break
    old, new = "{" + _SAME[kind] + "}", "{" + _OTHER[kind] + "}"
    end = max(text.index(old) + len(old), text.index(new) + len(new))
    cut = text.find(", ", end)
    return text if cut < 0 else text[:cut]


def _pair(
    sit: str,
    lang: str,
    kind: str,
    plain: str,
    excl: str,
    fix: str,
    fact: str,
    n: tuple[int, int] = (2, 12),
    g: str = "",
) -> tuple[Tpl, Tpl]:
    """One value fact as two templates: the exclusive form and the corrected form."""
    value = tpl(
        sit, lang, excl, "value", that=fact.replace("{v}", "{" + _OTHER[kind] + "}"), n=n, g=g
    )
    corr = tpl(
        sit,
        lang,
        plain,
        "corr",
        "any",
        that=fact.replace("{v}", "{" + _SAME[kind] + "}"),
        n=n,
        g=g,
        fix=fix,
        fixq=fix_quote(fix, kind),
    )
    return value, corr


