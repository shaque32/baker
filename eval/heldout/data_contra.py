"""Records that rule an assumption out: other values, denials, negations, incompatible states.

Tags: value (an exclusive value; the assumption carries the other one, {v} -> {m}), corr (a plain
value the sender later corrects in `fix`; the assumption carries the original, {v} -> {n}), deny
(the sender denies the act in `vp` after the accusation in `ask`), neg (the assumption's words
inside a negation), state (a fact incompatible with the assumption on the record's own date).
"""

from __future__ import annotations

from eval.heldout.registry import Tpl, tpl

_OTHER = {"n": "m", "place": "place2", "day": "day2"}
_SAME = {"n": "n", "place": "place", "day": "day"}


def _pair(
    sit: str,
    lang: str,
    kind: str,
    plain: str,
    excl: str,
    fix: str,
    fact: str,
    n: tuple[int, int] = (2, 12),
    g: str = "",
    quote_excl: str = "",
) -> tuple[Tpl, Tpl]:
    """One value fact as two templates: the exclusive form and the corrected form."""
    value = tpl(
        sit,
        lang,
        excl,
        "value",
        that=fact.replace("{v}", "{" + _OTHER[kind] + "}"),
        n=n,
        g=g,
        quote=quote_excl,
    )
    corr = tpl(
        sit,
        lang,
        plain,
        "corr",
        "any",
        that=fact.replace("{v}", "{" + _SAME[kind] + "}"),
        n=n,
        g=g,
        fix=fix,
    )
    return value, corr


