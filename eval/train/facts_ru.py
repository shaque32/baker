"""Russian facts, built by a small grammar so every record form keeps one literal verb.

A Russian fact is a past-tense verb ("заплатил{l}"), its first-person future ("заплачу") and an
object phrase with the value ("сантехнику {v}"). The grammar derives the stated, negated,
planned, conditional, asked, hedged and reported forms from them, so the English assumption
("paid the plumber {v} rubles") stays a dictionary translation of the record (guide rule 6;
the pairs are listed in eval/train/glossary.py). "{l}" is the speaker's past-tense ending ("" or
"а"), "{m}" the addressee's, "{k}" the third person's, "{n}" the third person's name.
"""

from __future__ import annotations

from eval.train.facts import CONDITIONS_RU, Fact


def R(key: str, scene: str, claim: str, claim_base: str, values: tuple[str, ...], *, past: str,
      fut: str, obj: str, shown: tuple[str, ...] = (), exact: tuple[str, ...] = (),
      extra: tuple[str, ...] = (), general: tuple[str, ...] = ()) -> Fact:  # fmt: skip
    pm, pk = past.replace("{l}", "{m}"), past.replace("{l}", "{k}")
    if not exact:
        exact = (f"{past} {obj.replace('{v}', 'ровно {v}')}, ни больше ни меньше",)
    return Fact(
        key, scene, "ru", "", "", claim, claim_base, values, shown=shown, exact=exact,
        extra=extra, general=general,
        done=(f"{past} {obj}", f"{obj} {past}", f"я {past} {obj}", f"да, {past} {obj}"),
        neg=(f"не {past} {obj}", f"{obj} не {past}", f"так и не {past} {obj}",
             f"нет, не {past} {obj}"),
        plan=(f"завтра {fut} {obj}", f"{fut} {obj} на неделе", f"{fut} {obj} после работы",
              f"{fut} {obj}, обещаю"),
        cond=tuple(f"{c}, {fut} {obj}" for c in CONDITIONS_RU)
        + tuple(f"{fut} {obj}, {c}" for c in CONDITIONS_RU),
        q=(f"ты {pm} {obj}?", f"{obj} {pm}?", f"{pm} {obj}? да или нет", f"а ты {pm} {obj}?"),
        hedge=(f"вроде {past} {obj}", f"кажется {past} {obj}, не помню", f"{past} {obj}, кажется",
               f"по-моему {past} {obj}, не уверен{{l}}"),
        hear=(f"{{n}} говорит, что {pk} {obj}", f"{{n}} сказал{{k}}, что {pk} {obj}",
              f"{{n}} написал{{k}}, что {pk} {obj}"),
    )  # fmt: skip


