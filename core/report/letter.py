"""Selection audit: a draft request for the full extraction when only curated reports were supplied.

An examiner-curated report holds only what the examiner chose to include. When a case's evidence
sources are curated reports (or of unknown coverage), Baker drafts a request, for counsel to
review and send, for each phone's full extraction and the extraction summary. The draft is built
from the imported sources only: file names, SHA-256 hashes, tool and version, extraction type and
dates as each report states them. Bracketed fields are for counsel to fill in. It is a draft,
not legal advice, and Baker never sends it anywhere.
"""

from __future__ import annotations

import html
import sqlite3
from dataclasses import dataclass

from core.restore.store import load_excerpts, load_exhibits

LETTER_VERSION = "1.0.0"


@dataclass(frozen=True)
class SourceLine:
    id: str
    file_name: str
    fidelity: str
    extraction_type: str
    sha256: str
    tool: str
    extracted_at_utc: str | None
    device: str | None
    messages: int


def _evidence_sources(conn: sqlite3.Connection) -> list[SourceLine]:
    rows = conn.execute(
        "SELECT s.id, s.file_name, s.fidelity, s.extraction_type, s.sha256,"
        " trim(coalesce(s.tool_name, '') || ' ' || coalesce(s.tool_version, '')),"
        " s.extracted_at_utc, (SELECT group_concat(d.label, '; ') FROM devices d"
        " WHERE d.source_id = s.id), (SELECT COUNT(*) FROM messages m WHERE m.source_id = s.id)"
        " FROM sources s WHERE s.kind != 'govdoc' ORDER BY s.id"
    )
    return [SourceLine(*r) for r in rows]


def needs_request(conn: sqlite3.Connection) -> list[SourceLine]:
    """The evidence sources a full extraction is requested for: every curated report and every
    source of unknown coverage. Empty when every source is a full extraction (or none exist)."""
    return [s for s in _evidence_sources(conn) if s.fidelity != "full_extraction"]


def _exhibits_not_found(conn: sqlite3.Connection) -> list[tuple[str, int, int]]:
    """(exhibit label, quoted messages not found, quoted messages) for each exhibit with a miss."""
    out = []
    for ex in load_exhibits(conn):
        excerpts = load_excerpts(conn, ex.id)
        missing = sum(
            1
            for x in excerpts
            if conn.execute(
                "SELECT 1 FROM exhibit_matches WHERE excerpt_id = ? LIMIT 1", (x.id,)
            ).fetchone()
            is None
        )
        if missing:
            out.append((ex.label, missing, len(excerpts)))
    return out


def request_letter(conn: sqlite3.Connection) -> str | None:
    """The draft as plain text, or None when no source needs it."""
    srcs = needs_request(conn)
    if not srcs:
        return None
    full = [s for s in _evidence_sources(conn) if s.fidelity == "full_extraction"]
    lines = [
        "DRAFT FOR COUNSEL'S REVIEW. Generated by Baker from the imported sources. Not legal "
        "advice. Check every detail against the discovery before sending.",
        "",
        "[Date]",
        "",
        "[Name], [Title]",
        "[Office of the prosecuting attorney]",
        "[Address]",
        "",
        "Re: [Case caption], [Case number]. Request for complete phone extractions and "
        "extraction documentation",
        "",
        "Dear [Name]:",
        "",
        "The phone evidence produced in discovery so far consists of the examiner-generated "
        "report(s) listed below. A report of this kind contains only the records the examiner "
        "chose to include, so it does not show the full contents of the extraction it was "
        "generated from. To review that evidence completely, the defense requests the following "
        "for each device listed:",
        "",
        "1. The complete forensic extraction in its native format (for example the full "
        "extraction package or image produced by the acquisition tool, and any reader package "
        "made from it), with its hash values.",
        "2. The extraction summary or acquisition report: acquisition method and extraction type, "
        "tool name and version, date and time of acquisition, the examiner, and the hash "
        "verification results.",
        "3. A description of how the report was produced from the extraction: the filters, "
        "search terms, categories, date ranges, tags or bookmarks used to select records, and "
        "the time zone and display settings applied.",
        "4. The examiner's notes and any processing logs for the extraction and the report.",
        "",
        "Reports produced so far:",
        "",
    ]
    for n, s in enumerate(srcs, start=1):
        coverage = (
            "examiner-curated report"
            if s.fidelity == "curated_report"
            else "coverage not stated in the file"
        )
        lines += [
            f"  {n}. {s.file_name} ({coverage})",
            f"     Device: {s.device or '[not stated in the report]'}",
            f"     Extraction type as reported: {s.extraction_type.replace('_', ' ')}",
            f"     Tool as reported: {s.tool or '[not stated in the report]'}",
            f"     Extraction date as reported: {s.extracted_at_utc or '[not stated]'}"
            + (" (UTC)" if s.extracted_at_utc else ""),
            f"     SHA-256 of the file received: {s.sha256}",
        ]
    missing = _exhibits_not_found(conn)
    if missing:
        lines += [
            "",
            "In addition, some messages quoted in the government's exhibits could not be "
            "located in the report(s) above, so the defense cannot review them in context:",
            "",
        ]
        lines += [
            f"  - {label}: {m} of {n} quoted message{'' if n == 1 else 's'} not located"
            for label, m, n in missing
        ]
        lines += [
            "",
            "Please produce the native records for those messages with their surrounding "
            "conversations, or identify where they appear in the material already produced.",
        ]
    if full:
        lines += [
            "",
            "A full extraction was already produced for: "
            + "; ".join(s.file_name for s in full)
            + ". This request covers the other sources only.",
        ]
    lines += [
        "",
        "Please let me know when these materials will be available, or contact me to arrange "
        "a time to inspect them.",
        "",
        "Sincerely,",
        "",
        "[Name]",
        "[Counsel for the defendant]",
        "",
        f"(Baker request draft {LETTER_VERSION})",
    ]
    return "\n".join(lines)


def letter_section(conn: sqlite3.Connection) -> str:
    """The report's selection-audit section: the draft request, or a line saying none is needed."""
    out = ["<h2 id='selection-audit'>Selection audit</h2>"]
    text = request_letter(conn)
    srcs = needs_request(conn)
    if text is None:
        out.append(
            "<p>Every evidence source in this case is recorded as a full extraction, so no "
            "request for one is drafted.</p>"
            if _evidence_sources(conn)
            else "<p class='muted'>No evidence source is imported.</p>"
        )
        return "".join(out)
    names = ", ".join(html.escape(s.file_name) for s in srcs)
    out.append(
        f"<p>This audit covers what the supplied reports contain: {names}. Records an examiner "
        "left out of a curated report were not available to Baker, so a finding here can change "
        "once the full extraction is reviewed. Below is a draft request for the full "
        "extraction and the extraction summary, for counsel to review. It is not legal advice "
        "and Baker does not send it.</p>"
        f"<pre class='letter'>{html.escape(text)}</pre>"
    )
    return "".join(out)
